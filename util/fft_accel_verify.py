import argparse
import json
import math
import os
import random
import re
import subprocess
import sys
from pathlib import Path

N = 4096
DEFAULT_CASES = [
    "zero",
    "impulse",
    "dc",
    "nyquist",
    "single_bin_7_cos",
    "single_bin_123_sin",
    "multi_tone",
    "random_seed_1",
    "random_seed_2",
    "boundary_alt",
    "overflow_stress",
]


def repo_root() -> Path:
    return Path(__file__).resolve().parents[1]


def clip_i16(values):
    clipped = []
    for value in values:
        rounded = int(round(value))
        if rounded > 32767:
            rounded = 32767
        if rounded < -32768:
            rounded = -32768
        clipped.append(rounded)
    return clipped


def tone(k, amp=4096, phase=0.0, kind="cos"):
    values = []
    for n in range(N):
        angle = 2.0 * math.pi * k * n / N + phase
        values.append(amp * (math.sin(angle) if kind == "sin" else math.cos(angle)))
    return values


def add_vectors(*vectors):
    return [sum(items) for items in zip(*vectors)]


def make_case(name: str):
    if name == "zero":
        return [0] * N
    if name == "impulse":
        values = [0] * N
        values[0] = 32767
        return values
    if name == "dc":
        return [2048] * N
    if name == "nyquist":
        return [4096 if (i & 1) == 0 else -4096 for i in range(N)]
    if name == "single_bin_7_cos":
        return clip_i16(tone(7, amp=8192, kind="cos"))
    if name == "single_bin_123_sin":
        return clip_i16(tone(123, amp=8192, kind="sin"))
    if name == "multi_tone":
        values = add_vectors(
            tone(3, amp=4096, phase=0.25, kind="cos"),
            tone(17, amp=3072, phase=-0.7, kind="sin"),
            tone(511, amp=2048, phase=1.1, kind="cos"),
            [777] * N,
        )
        return clip_i16(values)
    if name == "random_seed_1":
        rng = random.Random(1)
        return [rng.randint(-12000, 12000) for _ in range(N)]
    if name == "random_seed_2":
        rng = random.Random(2)
        return [rng.randint(-20000, 20000) for _ in range(N)]
    if name == "boundary_alt":
        pattern = [32767, -32768, 32760, -32760, 0, 1, -1, 16384]
        return [pattern[i % len(pattern)] for i in range(N)]
    if name == "overflow_stress":
        values = add_vectors(
            tone(1, amp=22000, phase=0.0, kind="cos"),
            tone(2, amp=18000, phase=0.4, kind="cos"),
            tone(5, amp=14000, phase=-0.9, kind="sin"),
        )
        return clip_i16(values)
    raise ValueError(f"unknown case {name!r}")


def selected_cases(names):
    if names == ["all"]:
        names = DEFAULT_CASES
    return [(name, make_case(name)) for name in names]


def write_header(path: Path, cases, run_fft=True, run_ifft=False):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="ascii") as f:
        f.write("// Generated by util/fft_accel_verify.py. Do not edit by hand.\n")
        f.write("#ifndef FFT_ACCEL_VECTORS_H_\n#define FFT_ACCEL_VECTORS_H_\n\n")
        f.write("#include <stdint.h>\n#include <stddef.h>\n\n")
        f.write(f"#define FFT_VERIFY_NUM_CASES {len(cases)}\n")
        f.write(f"#define FFT_VERIFY_RUN_FFT {1 if run_fft else 0}\n")
        f.write(f"#define FFT_VERIFY_RUN_IFFT {1 if run_ifft else 0}\n\n")
        f.write("static const char *const fft_verify_case_names[FFT_VERIFY_NUM_CASES] = {\n")
        for name, _ in cases:
            f.write(f'    "{name}",\n')
        f.write("};\n\n")
        f.write("static const size_t fft_verify_case_name_lens[FFT_VERIFY_NUM_CASES] = {\n")
        for name, _ in cases:
            f.write(f"    {len(name)},\n")
        f.write("};\n\n")
        f.write("static const int16_t fft_verify_vectors[FFT_VERIFY_NUM_CASES][4096] = {\n")
        for name, values in cases:
            f.write(f"    // {name}\n")
            f.write("    {\n")
            for offset in range(0, N, 16):
                chunk = ", ".join(str(int(v)) for v in values[offset : offset + 16])
                f.write(f"        {chunk},\n")
            f.write("    },\n")
        f.write("};\n\n")
        f.write("#endif // FFT_ACCEL_VECTORS_H_\n")


def run_cmd(cmd, cwd, log_path=None, check=True):
    if log_path is None:
        proc = subprocess.run(cmd, cwd=cwd, text=True)
    else:
        with log_path.open("w", encoding="utf-8", errors="replace") as f:
            proc = subprocess.run(cmd, cwd=cwd, stdout=f, stderr=subprocess.STDOUT, text=True)
    if check and proc.returncode != 0:
        raise RuntimeError(f"command failed ({proc.returncode}): {' '.join(cmd)}")
    return proc.returncode


def build_elf(root: Path, artifacts: Path):
    make_log = artifacts / "build_fft_accel_dump.log"
    flags = (
        "-DOT_PLATFORM_RV32 -march=rv64gc_zifencei -mabi=lp64d -mstrict-align "
        "-O2 -Wall -Wextra -static -ffunction-sections -fdata-sections "
        "-frandom-seed=cheshire"
    )
    cmd = ["make", "sw/tests/fft_accel_dump.spm.elf", f"CHS_SW_FLAGS={flags}"]
    run_cmd(cmd, root, make_log)
    return root / "sw/tests/fft_accel_dump.spm.elf"


def run_vcs(root: Path, elf: Path, artifacts: Path):
    vcs_dir = root / "target/sim/vcs"
    sim_log = artifacts / "fft_accel_dump.vcs.log"
    env_cmd = f"SELCFG=4 BINARY={elf} EXTRA_SIM_ARGS=+FFT_DUT_WRITES ./start.cheshire_soc.sh"
    with sim_log.open("w", encoding="utf-8", errors="replace") as f:
        proc = subprocess.run(["bash", "-lc", env_cmd], cwd=vcs_dir, stdout=f, stderr=subprocess.STDOUT)
    if proc.returncode != 0:
        raise RuntimeError(f"VCS simulation failed ({proc.returncode}); see {sim_log}")
    text = sim_log.read_text(encoding="utf-8", errors="replace")
    if "FFT_VERIFY_DONE" not in text or "[JTAG] SUCCESS" not in text:
        raise RuntimeError(f"simulation did not finish cleanly; see {sim_log}")
    return sim_log


def parse_i32(hex8):
    value = int(hex8, 16)
    if value & 0x80000000:
        value -= 0x100000000
    return value


def parse_dut_log(log_path: Path):
    uart_pattern = re.compile(r"FFT_DUT\s+(\S+)\s+(fft|ifft)\s+([0-9a-fA-F]{8})\s+([0-9a-fA-F]{16})")
    begin_pattern = re.compile(r"FFT_DUMP_BEGIN case=(\S+) mode=(fft|ifft) n=4096")
    end_pattern = re.compile(r"FFT_DUMP_END case=(\S+) mode=(fft|ifft)")
    write_pattern = re.compile(r"\[fft_task_ctrl\] dut-write trans=\d+ inverse=[01] idx=(\d+) data=([0-9a-fA-F]{16})")
    outputs = {}
    current = None
    for line in log_path.read_text(encoding="utf-8", errors="replace").splitlines():
        begin = begin_pattern.search(line)
        if begin:
            current = (begin.group(1), begin.group(2))
            outputs.setdefault(current, [0j] * N)
            continue

        end = end_pattern.search(line)
        if end:
            current = None
            continue

        match = uart_pattern.search(line)
        if match:
            case, mode, idx_hex, word = match.groups()
            idx = int(idx_hex, 16)
            key = (case, mode)
        else:
            match = write_pattern.search(line)
            if not match or current is None:
                continue
            idx_text, word = match.groups()
            idx = int(idx_text, 10)
            key = current

        imag = parse_i32(word[:8])
        real = parse_i32(word[8:])
        outputs.setdefault(key, [0j] * N)[idx] = complex(real, imag)
    return outputs


def bit_reverse_indices(n):
    bits = int(math.log2(n))
    indices = []
    for value in range(n):
        x = value
        y = 0
        for _ in range(bits):
            y = (y << 1) | (x & 1)
            x >>= 1
        indices.append(y)
    return indices


def fft_unscaled_real(values, inverse=False):
    a = [complex(v, 0.0) for v in values]
    rev = bit_reverse_indices(len(a))
    a = [a[i] for i in rev]

    size = 2
    sign = 1.0 if inverse else -1.0
    while size <= len(a):
        angle = sign * 2.0 * math.pi / size
        wlen = complex(math.cos(angle), math.sin(angle))
        half = size // 2
        for start in range(0, len(a), size):
            w = 1.0 + 0.0j
            for j in range(half):
                u = a[start + j]
                v = a[start + j + half] * w
                a[start + j] = u + v
                a[start + j + half] = u - v
                w *= wlen
        size *= 2
    return a


def energy(values):
    return sum((x.real * x.real + x.imag * x.imag) for x in values)


def fit_scale(ref, dut):
    denom = energy(ref)
    if denom == 0.0:
        return 0.0
    num = 0.0 + 0.0j
    for r, d in zip(ref, dut):
        num += r.conjugate() * d
    return (num / denom).real


def snr_db(ref, dut):
    signal = energy(ref)
    noise = energy([d - r for r, d in zip(ref, dut)])
    if signal == 0.0 and noise == 0.0:
        return 999.0
    if noise == 0.0:
        return 999.0
    return 10.0 * math.log10(signal / noise)


def compare_case(name, mode, values, dut, maxerr_limit, snr_limit, scale_tol):
    ref_natural = fft_unscaled_real(values, inverse=(mode == "ifft"))
    rev = bit_reverse_indices(N)
    inv_rev = [0] * N
    for idx, ridx in enumerate(rev):
        inv_rev[ridx] = idx
    candidates = {
        "natural": ref_natural,
        "bit_reversed_ref": [ref_natural[i] for i in rev],
        "bit_reversed_dut": [ref_natural[i] for i in inv_rev],
    }

    best = None
    for order, ref in candidates.items():
        scale = fit_scale(ref, dut)
        scaled_ref = [x * scale for x in ref]
        abs_err = [abs(d - r) for r, d in zip(scaled_ref, dut)]
        worst_index = max(range(N), key=lambda i: abs_err[i])
        result = {
            "case": name,
            "mode": mode,
            "order": order,
            "scale": scale,
            "scale_error_vs_2^-5": scale - (1.0 / 32.0),
            "max_abs_error": max(abs_err),
            "mean_abs_error": sum(abs_err) / len(abs_err),
            "snr_db": snr_db(scaled_ref, dut),
            "worst_index": worst_index,
        }
        if best is None or (result["snr_db"], -result["max_abs_error"]) > (
            best["snr_db"],
            -best["max_abs_error"],
        ):
            best = result

    zero_case = all(v == 0 for v in values)
    if zero_case:
        best["pass"] = best["max_abs_error"] <= maxerr_limit
        best["scale_ok"] = True
    else:
        best["scale_ok"] = abs(best["scale"] - (1.0 / 32.0)) <= scale_tol
        best["pass"] = (
            best["order"] == "natural"
            and best["scale_ok"]
            and best["max_abs_error"] <= maxerr_limit
            and best["snr_db"] >= snr_limit
        )
    return best


def save_arrays(artifacts: Path, cases, outputs, modes):
    arr_dir = artifacts / "arrays"
    arr_dir.mkdir(parents=True, exist_ok=True)
    for name, values in cases:
        (arr_dir / f"{name}.input.txt").write_text(
            "\n".join(str(v) for v in values) + "\n", encoding="ascii"
        )
        for mode in modes:
            key = (name, mode)
            if key not in outputs:
                continue
            dut = outputs[key]
            ref = [x / 32.0 for x in fft_unscaled_real(values, inverse=(mode == "ifft"))]
            with (arr_dir / f"{name}.{mode}.dut.txt").open("w", encoding="ascii") as f:
                for value in dut:
                    f.write(f"{int(value.real)} {int(value.imag)}\n")
            with (arr_dir / f"{name}.{mode}.golden_float_scaled.txt").open("w", encoding="ascii") as f:
                for value in ref:
                    f.write(f"{value.real:.8f} {value.imag:.8f}\n")


def main():
    parser = argparse.ArgumentParser(description="Run FFT accelerator SoC verification with Python golden.")
    parser.add_argument("--cases", nargs="+", default=["all"], help="case names or 'all'")
    parser.add_argument("--modes", default="fft", choices=["fft", "ifft", "both"])
    parser.add_argument("--artifacts", default="target/fft_verify")
    parser.add_argument("--maxerr", type=float, default=128.0)
    parser.add_argument("--stress-maxerr", type=float, default=768.0)
    parser.add_argument("--snr", type=float, default=34.0)
    parser.add_argument("--stress-snr", type=float, default=20.0)
    parser.add_argument("--scale-tol", type=float, default=0.003)
    parser.add_argument("--no-run", action="store_true", help="only generate header")
    args = parser.parse_args()

    root = repo_root()
    artifacts = root / args.artifacts
    artifacts.mkdir(parents=True, exist_ok=True)

    cases = selected_cases(args.cases)
    run_fft = args.modes in ("fft", "both")
    run_ifft = args.modes in ("ifft", "both")
    modes = []
    if run_fft:
        modes.append("fft")
    if run_ifft:
        modes.append("ifft")

    header = root / "sw/tests/fft_accel_vectors.h"
    write_header(header, cases, run_fft=run_fft, run_ifft=run_ifft)

    manifest = {
        "cases": [name for name, _ in cases],
        "modes": args.modes,
        "n": N,
        "header": str(header.relative_to(root)),
    }
    (artifacts / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")

    if args.no_run:
        print(f"generated {header}")
        return 0

    elf = build_elf(root, artifacts)
    log_path = run_vcs(root, elf, artifacts)
    outputs = parse_dut_log(log_path)

    results = []
    failures = []
    for name, values in cases:
        for mode in modes:
            key = (name, mode)
            if key not in outputs:
                failures.append(f"missing DUT output for {name}/{mode}")
                continue
            if "overflow" in name or "boundary" in name or "random_seed_2" in name:
                maxerr = args.stress_maxerr
                snr = args.stress_snr
            else:
                maxerr = args.maxerr
                snr = args.snr
            result = compare_case(name, mode, values, outputs[key], maxerr, snr, args.scale_tol)
            result["maxerr_limit"] = maxerr
            result["snr_limit"] = snr
            results.append(result)
            if not result["pass"]:
                failures.append(
                    f"{name}/{mode} failed: order={result['order']} "
                    f"scale={result['scale']:.8f} maxerr={result['max_abs_error']:.3f} "
                    f"snr={result['snr_db']:.2f}"
                )

    save_arrays(artifacts, cases, outputs, modes)
    summary = {"results": results, "failures": failures}
    (artifacts / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")

    for result in results:
        status = "PASS" if result["pass"] else "FAIL"
        print(
            f"{status} {result['case']}/{result['mode']}: "
            f"order={result['order']} scale={result['scale']:.8f} "
            f"maxerr={result['max_abs_error']:.3f} snr={result['snr_db']:.2f}dB "
            f"worst={result['worst_index']}"
        )

    if failures:
        print("\nFailures:")
        for failure in failures:
            print(f"  - {failure}")
        print(f"\nArtifacts: {artifacts}")
        return 1

    print(f"\nAll FFT accelerator checks passed. Artifacts: {artifacts}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
